// Controlli tecnici sul sito (regole in docs/07-segnali.md), condivisi dal motore
// («Valuta segnali sito», «Controlli tecnici sito») e dal workflow «Aziende | Controllo siti».
// Inserito al posto di __CONTROLLI_SITO__ da build.py / build.mjs.
//   html: homepage; website: URL del sito; oggi: AAAA-MM-GG; richiesti: codici da controllare;
//   https: esito della richiesta HTTPS ({ https_body } o { error }), solo per no_https.
// Ogni esito: pass (presente, con la prova), fail (assente), undetermined (non dimostrabile).
function controlliSito({ html, website, oggi, richiesti, https }) {
  const testo = html.replace(/<script[\s\S]*?<\/script>|<style[\s\S]*?<\/style>|<noscript[\s\S]*?<\/noscript>/gi, ' ')
    .replace(/<[^>]+>/g, ' ').replace(/&nbsp;|&#160;/gi, ' ').replace(/&copy;|&#169;/gi, '©').replace(/\s+/g, ' ').trim();
  // Pagine che non sono il sito dell'azienda (Data Quality, 21/10): blocchi anti-bot e pagine d'errore
  // (macron.com: «Request blocked» di CloudFront, letto come homepage senza privacy, viewport e lingue) e
  // pagine di trasloco verso un altro dominio (palmabit.com: «… diventa …, vai al nuovo sito»). Su queste
  // ogni segnale della homepage è «non determinabile».
  // Trasloco: pagina corta che rimanda a un altro dominio, con pochissimi link interni e una frase esplicita.
  // Solo i link <a>, esclusi social, mappe, font e servizi (Code Reviewer, 21/10: con Google Fonts o Facebook
  // e «nuovo sito produttivo» scattava su homepage vere).
  const dominio = String(website || '').toLowerCase().replace(/^https?:\/\//, '').replace(/^www\./, '').split(/[/?#:]/)[0];
  const SERVIZI = /(^|\.)(facebook|instagram|twitter|x|linkedin|youtube|youtu|tiktok|pinterest|whatsapp|wa|t|telegram|google|goo|gstatic|googleapis|maps|apple|tripadvisor|booking|airbnb|paypal|iubenda|cookiebot|wordpress|w3|schema|jquery|cloudflare|jsdelivr|bootstrapcdn|fontawesome|unpkg|wix|shopify|aruba|register|siteground)\.[a-z.]+$/;
  const ancore = [...html.matchAll(/<a\b[^>]*href\s*=\s*["']([^"'#]*)["']/gi)].map(m => m[1].trim());
  const hostDi = (u) => (u.match(/^(?:https?:)?\/\/([^/?#:]+)/i) || [])[1]?.toLowerCase().replace(/^www\./, '') || '';
  const altrove = ancore.map(hostDi).filter(h => h && dominio && h !== dominio && !h.endsWith('.' + dominio) && !SERVIZI.test(h));
  const interni = ancore.filter(u => { const h = hostDi(u); return u && !/^(mailto|tel|javascript):/i.test(u) && (!h || h === dominio || h.endsWith('.' + dominio)); });
  // Frase nel titolo, oppure nel testo di una pagina corta senza menu: le pagine di blocco non hanno menu, e
  // «appartamenti in vendita» o «server Plesk» in una homepage vera non la scartano (Code Reviewer, 21/10).
  const titolo = (html.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || [])[1] || '';
  const segno = (re, max) => testo.length < max && (re.test(titolo) || (interni.length <= 2 && re.test(testo)));
  const BLOCCO = /request blocked|request could not be satisfied|request unsuccessful|generated by cloudfront|access denied|attention required|just a moment\.\.\.|checking your browser|cf-browser-verification|ddos protection|security checkpoint|pardon our interruption|please enable (js|javascript)|enable javascript and cookies|your access to this site has been limited|403 forbidden|\b[a-z0-9-]+\.[a-z]{2,6} is for sale|this domain (is|may be) for sale|questo dominio [^.]{0,30}in vendita|il dominio [a-z0-9-]+\.[a-z]{2,6} [eè] in vendita|questo dominio [eè] (registrato|parcheggiato)|domain (is )?parked|parked (free|domain)|dominio (registrato|parcheggiato) (con|da|presso)|account suspended|default web site page|plesk (obsidian |onyx )?(web server|default page)/i;
  // Pagine di prova del server, verifiche anti-robot: frasi inequivocabili, ma pagine più lunghe (pagina di prova
  // di Apache 1984 caratteri, «Visitor anti-robot validation» 2258: Data Quality, 21/10).
  const BLOCCO_LUNGO = /test page for the apache|web server (installed )?at this site is working properly|welcome to nginx|apache2 (ubuntu|debian) default page|no ssl certificate (is )?configured|anti-robot validation|please enable js and disable any ad ?blocker|checking your request/i;
  // Pagine predefinite del server riconosciute solo dal titolo («It works!» può stare in una homepage vera).
  const bloccata = segno(BLOCCO, 1500) || segno(BLOCCO_LUNGO, 3000)
    || (testo.length < 1500 && /^\s*(it works!?|welcome to nginx!?|apache2? [^<]*default page|index of \/)/i.test(titolo));
  // Errore momentaneo del server: segnali non determinabili, ma le prove già salvate restano (Code Reviewer, 21/10).
  const guasto = !bloccata && segno(/404 not found|500 internal server error|502 bad gateway|503 service (temporarily )?unavailable|504 gateway time-?out|briefly unavailable for scheduled maintenance|errore critico sul tuo sito|critical error on (this|your) website/i, 3000);
  // Pagina provvisoria («in costruzione», «sito in manutenzione»): vale il segnale under_construction, ma
  // gli altri segnali della homepage non dicono niente del sito vero (radiciviaggi.it, 21/10).
  const PROVVISORIA = /in costruzione|coming soon|under construction|en construcci[oó]n|en construction|bient[oô]t en ligne|in k[uü]rze|im aufbau|sito in manutenzione|maintenance mode|torneremo presto online/i;
  // Solo frasi che indicano un trasloco, non «nuovo sito» da solo (Data Quality, 21/10: «Online il nuovo Sito Web»
  // con il link all'agenzia su borgoverde.eu, «Stiamo sviluppando il nuovo sito» su una pagina coming soon).
  const trasloco = testo.length < 2000 && altrove.length > 0 && interni.length <= 2 && !PROVVISORIA.test(testo)
    && /vai al nuovo|visita il (nostro )?nuovo sito|nuovo sito [eè] (online )?(su|a|all'indirizzo)|nuovo indirizzo (web|internet|del sito)|ci siamo (trasferiti|spostati)|abbiamo cambiato (sito|indirizzo web|nome)|we(?: have|'ve) moved|visit our new|our new website is|nous avons d[ée]m[ée]nag/i.test(testo);
  const leggibile = html.length > 200 && /<html|<body|<head/i.test(html) && !bloccata && !guasto && !trasloco;
  const contenuto = testo.length >= 200;
  // La frase nel titolo o nell'h1, oppure in una pagina corta senza menu: «appartamenti in costruzione» o «coming soon»
  // in una sezione di una homepage vera non la rendono provvisoria (Code Reviewer, 21/10).
  const titoli = `${titolo} ${[...html.matchAll(/<h1[^>]*>([\s\S]*?)<\/h1>/gi)].map(m => m[1]).join(' ')}`;
  const provvisoria = leggibile && testo.length < 800 && (PROVVISORIA.test(titoli) || (interni.length <= 2 && PROVVISORIA.test(testo)));
  const vera = leggibile && !provvisoria;
  const anno = Number(oggi.slice(0, 4));

  // Tabella delle versioni (da src/lib/domain/cms-releases.json, inserita dalla build).
  const RILASCI = __CMS_RELEASES__;
  const v2n = (v) => String(v).split('.').map(x => parseInt(x, 10) || 0);
  const cmp = (a, b) => { const x = v2n(a), y = v2n(b); for (let i = 0; i < 3; i++) { const d = (x[i] || 0) - (y[i] || 0); if (d) return d; } return 0; };
  const limite = `${anno - 2}${oggi.slice(4)}`; // oggi meno 2 anni (AAAA-MM-GG)
  const vecchia = (cms, versione) => {
    const tab = RILASCI[cms] || [];
    const mm = versione.split('.').slice(0, 2).join('.');
    const nota = tab.find(([v]) => v === mm);
    if (nota && nota[1] <= limite) return nota[1];
    const dopo = tab.find(([v, d]) => cmp(v, versione) > 0 && d <= limite);
    return dopo ? `prima del ${dopo[1]}` : '';
  };

  const esiti = {};
  const metti = (code, status, detail = '') => {
    esiti[code] = { code, status, evidence: { detail, url: website, checked_at: oggi } };
  };

  // Tecnologie (filtro di segmentazione, sempre calcolate quando si valutano segnali).
  const tecnologie = [];
  if (/wp-content|wp-includes|name=["']generator["'][^>]*wordpress/i.test(html)) tecnologie.push('wordpress');
  if (/woocommerce/i.test(html)) tecnologie.push('woocommerce');
  if (/name=["']generator["'][^>]*joomla|\/media\/jui\/|\/components\/com_/i.test(html)) tecnologie.push('joomla');
  if (/static\.wixstatic\.com|wix\.com|_wixCIDX|X-Wix/i.test(html)) tecnologie.push('wix');
  if (/cdn\.shopify\.com|Shopify\.theme/i.test(html)) tecnologie.push('shopify');

  if (richiesti.includes('no_mobile')) {
    if (!vera) metti('no_mobile', 'undetermined');
    else if (/<meta[^>]+name=["']?viewport/i.test(html)) metti('no_mobile', 'fail');
    else if (/<link[^>]+rel=["']alternate["'][^>]+media=["'][^"']*max-width/i.test(html) || /href=["']https?:\/\/m\./i.test(html)) metti('no_mobile', 'fail', 'versione mobile separata');
    // Presente solo con testo vero: pagine quasi vuote o di blocco sconosciute non dimostrano niente (QA, 21/10).
    else if (!contenuto) metti('no_mobile', 'undetermined');
    else metti('no_mobile', 'pass', 'Homepage senza impostazione per dispositivi mobili');
  }

  if (richiesti.includes('outdated_cms')) {
    const versioni = [];
    for (const m of html.matchAll(/name=["']generator["'][^>]*content=["']([^"']+)["']|content=["']([^"']+)["'][^>]*name=["']generator["']/gi)) {
      const g = m[1] || m[2] || '';
      const wp = g.match(/WordPress\s+(\d+\.\d+(?:\.\d+)?)/i); if (wp) versioni.push(['wordpress', wp[1]]);
      const jo = g.match(/Joomla!?\s*(?:-\s*Open Source Content Management\s*)?(\d+\.\d+(?:\.\d+)?)/i); if (jo) versioni.push(['joomla', jo[1]]);
      const wc = g.match(/WooCommerce\s+(\d+\.\d+(?:\.\d+)?)/i); if (wc) versioni.push(['woocommerce', wc[1]]);
    }
    if (!versioni.some(([c]) => c === 'wordpress')) {
      // Solo i file che portano la versione di WordPress: le librerie in wp-includes hanno la
      // propria (jquery.min.js?ver=3.7.1 è jQuery 3.7.1, non WordPress 3.7.1).
      const ver = html.match(/\/wp-includes\/(?:js\/(?:wp-emoji-release|wp-embed|comment-reply)(?:\.min)?\.js|css\/(?:dist\/block-library\/style|dashicons|admin-bar)(?:\.min)?\.css)\?ver=(\d+\.\d+(?:\.\d+)?)/i);
      if (ver) versioni.push(['wordpress', ver[1]]);
    }
    const NOMI = { wordpress: 'WordPress', joomla: 'Joomla', woocommerce: 'WooCommerce' };
    const vecchie = versioni.map(([c, v]) => [c, v, vecchia(c, v)]).filter(x => x[2]);
    if (!leggibile || !versioni.length) metti('outdated_cms', 'undetermined');
    else if (vecchie.length) metti('outdated_cms', 'pass', vecchie.map(([c, v, d]) => `${NOMI[c]} ${v} (${/^\d/.test(d) ? `versione del ${d}` : d})`).join(', '));
    else metti('outdated_cms', 'fail', versioni.map(([c, v]) => `${NOMI[c]} ${v}`).join(', '));
  }

  if (richiesti.includes('single_language')) {
    const LINGUE = 'en|de|fr|es|it|pt|nl|pl|cs|ru|zh|ja';
    const altre = /hreflang=["'](?!x-default)[a-z]{2}/i.test(html)
      || new RegExp(`href=["'](?:https?://[^"'/]+)?/(?:${LINGUE})(?:[-_][a-z]{2})?/?["'/?#]`, 'i').test(html)
      || /[?&](?:lang|language|lng)=[a-z]{2}/i.test(html)
      || new RegExp(`href=["']https?://(?:${LINGUE})\\.`, 'i').test(html)
      || new RegExp(`>\\s*(?:${LINGUE.toUpperCase()})\\s*</a>`).test(html);
    const lingua = (html.match(/<html[^>]+lang=["']([a-z]{2})/i) || [])[1] || '';
    if (!vera || !contenuto) metti('single_language', 'undetermined');
    else if (altre) metti('single_language', 'fail');
    else metti('single_language', 'pass', `Nessuna versione in altre lingue${lingua ? ` (lingua: ${lingua})` : ''}`);
  }

  if (richiesti.includes('stale_copyright')) {
    const anni = [...testo.matchAll(/(?:©|copyright)[^0-9]{0,30}((?:19|20)\d{2})(?:\s*[-–]\s*((?:19|20)\d{2}))?/gi)]
      .map(m => Number(m[2] || m[1])).filter(y => y >= 1995 && y <= anno + 1);
    if (!vera || !contenuto || !anni.length) metti('stale_copyright', 'undetermined');
    else {
      const ultimo = Math.max(...anni);
      if (anno - ultimo >= 3) metti('stale_copyright', 'pass', `Copyright fermo al ${ultimo}`);
      else metti('stale_copyright', 'fail', `Copyright ${ultimo}`);
    }
  }

  if (richiesti.includes('under_construction')) {
    if (!leggibile) metti('under_construction', 'undetermined');
    else if (provvisoria) metti('under_construction', 'pass', 'Homepage provvisoria');
    else metti('under_construction', 'fail');
  }

  if (richiesti.includes('no_booking_engine')) {
    const MOTORI = /simplebooking|vertical-?booking|octorate|bedzzle|ericsoft|cloudbeds|synxis|booking-?expert|passepartout|bookingsuite|hotelinone|blastness|5stelle|scrigno|wubook|bookassist|d-edge|availpro|smartbooking|roiback|mirai\.com|siteminder|thebookingbutton|littlehotelier|beds24|hotelrunner|guestcentric|travelclick|ihotelier|bookingengine/i;
    if (!vera) metti('no_booking_engine', 'undetermined');
    else if (MOTORI.test(html)) metti('no_booking_engine', 'fail');
    else if (!contenuto) metti('no_booking_engine', 'undetermined');
    else metti('no_booking_engine', 'pass', 'Nessun booking engine riconosciuto nella homepage');
  }

  if (richiesti.includes('no_privacy')) {
    // Segnale indicativo (punto 48 del 20/10): nessuna traccia di informativa privacy o di banner dei cookie
    // nella homepage. Prudente: basta una parola o un gestore dei consensi noto perché NON scatti, e le pagine
    // senza testo leggibile (siti costruiti dal browser) restano «non determinabile».
    const TRACCE = /privacy|cookie|informativa|gdpr|dati personali|protezione dei dati|trattamento dei dati|datenschutz|consent|consenso|iubenda|cookiebot|cookieyes|complianz|onetrust|cookie-?law|termly|usercentrics|quantcast|didomi/i;
    if (!vera || !contenuto) metti('no_privacy', 'undetermined');
    else if (TRACCE.test(html)) metti('no_privacy', 'fail');
    else metti('no_privacy', 'pass', "Nessun link all'informativa privacy né banner dei cookie nella homepage");
  }

  if (richiesti.includes('no_https')) {
    // Esito della richiesta HTTPS: presente solo se eseguita.
    const h = https;
    const eseguito = h && (h.https_body !== undefined || h.error !== undefined);
    // n8n mette il motivo vero in error.cause o in description («SSL Issue: …» da solo non dice nulla).
    const e = h?.error;
    const msg = [e?.message ?? e, e?.cause?.message, e?.description, h?.details?.description, e?.code].filter(Boolean).map(String).join(' | ');
    // Solo i difetti che anche un browser mostra (controllo del 19/10). Catena incompleta
    // («unable to verify the first certificate») e handshake rifiutati (EPROTO) di solito
    // passano nei browser: non dimostrano niente.
    const nome = /altname|does not match|ERR_TLS_CERT_ALTNAME/i.test(msg);
    const host = ((msg.match(/Host: ([a-z0-9.-]+?)\.? is not/i) || [])[1] || '').toLowerCase();
    const copreWww = host && msg.toLowerCase().includes('dns:www.' + host.replace(/^www\./, ''));
    // Certificato del marchio su un altro dominio (esprinet.it -> esprinet.com): dominio secondario
    // di un gruppo, il sito vero è altrove. Sul dominio nudo di un sito salvato in https non si sa
    // se il sito vero sta sul www (ricontrollo del 19/10): conta solo l'host che il sito usa davvero.
    const nomi = (msg.toLowerCase().split("cert's altnames:")[1] || '').split(' | ')[0];
    const etichetta = host.replace(/^www\./, '').split('.')[0];
    const marchio = etichetta.length >= 4 && nomi.includes(etichetta);
    const hostVero = /^http:\/\//i.test(website) || /^https?:\/\/www\./i.test(website);
    if (!eseguito) metti('no_https', 'undetermined');
    else if (!h.error) metti('no_https', 'fail');
    else if (/expired|CERT_HAS_EXPIRED/i.test(msg)) metti('no_https', 'pass', 'Certificato HTTPS scaduto');
    else if (/self.signed|SELF_SIGNED/i.test(msg)) metti('no_https', 'pass', 'Certificato HTTPS autofirmato');
    // Nome sbagliato: conta solo se il certificato non copre il www, non è del marchio e l'host è quello vero.
    else if (nome && !copreWww && !marchio && hostVero) metti('no_https', 'pass', 'Certificato HTTPS non valido per questo sito');
    else if (/ECONNREFUSED/i.test(msg) && /^http:\/\//i.test(website) && leggibile) metti('no_https', 'pass', 'Il sito non risponde in HTTPS');
    else metti('no_https', 'undetermined');
  }

  // Pagina che non è il sito: le vecchie prove dei segnali della homepage non valgono più. Il database le toglie
  // solo con questo segno (store_company_checks, migrazione 055), non per un sito momentaneamente spento.
  const HOME = ['no_mobile', 'single_language', 'stale_copyright', 'no_booking_engine', 'no_privacy', 'outdated_cms', 'under_construction'];
  const motivo = bloccata ? 'Pagina di blocco o di errore, non il sito' : trasloco ? 'Pagina di trasloco verso un altro sito' : '';
  for (const e of Object.values(esiti)) {
    if (e.status !== 'undetermined' || !HOME.includes(e.code)) continue;
    if (guasto) e.evidence = { ...e.evidence, detail: 'Errore momentaneo del server' };
    else if (motivo) e.evidence = { ...e.evidence, detail: motivo, invalid_page: true };
    else if (provvisoria && e.code !== 'outdated_cms' && e.code !== 'under_construction') e.evidence = { ...e.evidence, detail: 'Pagina provvisoria', invalid_page: true };
  }

  return { testo, esiti, tecnologie };
}
